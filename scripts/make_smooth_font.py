"""Convert a TrueType font into a TFT_eSPI smooth font (.vlw) stored as a C array.

Usage:
  python make_smooth_font.py FONT.ttf SIZE NAME [--chars TEXT] [--weight N]

  SIZE     pixel size of the font
  NAME     C array name, also used for the output file include/fonts/NAME.h
  --chars  characters to include (default: printable ASCII plus the degree sign)
  --weight weight to use from a variable font, e.g. 400 regular or 700 bold

Requires freetype-py (pip install freetype-py).
"""

import argparse
import struct
from pathlib import Path

import freetype

DEFAULT_CHARS = "".join(chr(code) for code in range(0x20, 0x7F)) + "°"


def build_vlw(font_path, size, chars, weight):
    face = freetype.Face(str(font_path))
    if weight is not None:
        axes = face.get_variation_info().axes
        coords = [weight if axis.tag == "wght" else axis.default for axis in axes]
        face.set_var_design_coords(coords)
    face.set_pixel_sizes(0, size)

    glyphs = []
    for char in dict.fromkeys(chars):
        if face.get_char_index(char) == 0:
            raise SystemExit(f"Font has no glyph for {char!r}")
        face.load_char(char, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
        slot = face.glyph
        bitmap = slot.bitmap
        rows = bytearray()
        for row in range(bitmap.rows):
            start = row * bitmap.pitch
            rows += bytes(bitmap.buffer[start:start + bitmap.width])
        glyphs.append({
            "code": ord(char),
            "height": bitmap.rows,
            "width": bitmap.width,
            "advance": round(slot.advance.x / 64),
            "top": slot.bitmap_top,
            "left": slot.bitmap_left,
            "bitmap": bytes(rows),
        })

    def glyph_metric(char, fallback):
        for glyph in glyphs:
            if glyph["code"] == ord(char):
                return glyph
        return fallback

    reference_ascent = glyph_metric("d", None)
    reference_descent = glyph_metric("p", None)
    ascent = reference_ascent["top"] if reference_ascent else max(g["top"] for g in glyphs)
    descent = (reference_descent["height"] - reference_descent["top"]) if reference_descent else \
        max(g["height"] - g["top"] for g in glyphs)

    data = bytearray(struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent))
    for glyph in glyphs:
        if glyph["width"] > 255 or glyph["height"] > 255 or glyph["advance"] > 255:
            raise SystemExit(f"Glyph {chr(glyph['code'])!r} is larger than 255 pixels")
        data += struct.pack(">7i", glyph["code"], glyph["height"], glyph["width"],
                            glyph["advance"], glyph["top"], glyph["left"], 0)
    for glyph in glyphs:
        data += glyph["bitmap"]
    return bytes(data), len(glyphs)


def write_header(path, name, data, source, size, glyph_count):
    lines = [
        "#pragma once",
        "",
        f"// Generated by scripts/make_smooth_font.py from {source}",
        f"// {size} px, {glyph_count} glyphs, {len(data)} bytes",
        "#include <pgmspace.h>",
        "",
        f"const uint8_t {name}[] PROGMEM = {{",
    ]
    for start in range(0, len(data), 20):
        chunk = data[start:start + 20]
        lines.append("  " + ", ".join(f"0x{byte:02X}" for byte in chunk) + ",")
    lines.append("};")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("font", type=Path)
    parser.add_argument("size", type=int)
    parser.add_argument("name")
    parser.add_argument("--chars", default=DEFAULT_CHARS)
    parser.add_argument("--weight", type=int)
    args = parser.parse_args()

    data, glyph_count = build_vlw(args.font, args.size, args.chars, args.weight)
    output = Path(__file__).resolve().parent.parent / "include" / "fonts" / f"{args.name}.h"
    source = args.font.name + (f" weight {args.weight}" if args.weight else "")
    write_header(output, args.name, data, source, args.size, glyph_count)
    print(f"Wrote {output} ({glyph_count} glyphs, {len(data)} bytes)")


if __name__ == "__main__":
    main()
